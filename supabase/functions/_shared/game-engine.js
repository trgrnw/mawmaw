function applyGameAction(s, action, now = Date.now()) {
  const a = action.args, id = String(a.id || ""), business = () => {
    const b = s.businesses.find((x) => x.id === id);
    if (!b) throw Error("\u041F\u0440\u0435\u0434\u043F\u0440\u0438\u044F\u0442\u0438\u0435 \u043D\u0435 \u043D\u0430\u0439\u0434\u0435\u043D\u043E");
    return b;
  };
  switch (action.type) {
    case "click": {
      const count = Number(a.count);
      if (!Number.isInteger(count) || count < 1 || count > 40) throw Error("Invalid click count");
      const available = Math.min(200, s.clickCredit + Math.max(0, now - s.clickCreditAt) / 1e3 * 20);
      if (count > available) throw Error("\u0421\u043B\u0438\u0448\u043A\u043E\u043C \u0447\u0430\u0441\u0442\u044B\u0435 \u043A\u043B\u0438\u043A\u0438");
      s.clickCredit = available - count;
      s.clickCreditAt = now;
      credit(s, s.clickPower * count);
      s.totalEarnedClick += s.clickPower * count;
      xp(s, count);
      break;
    }
    case "upgrade": {
      const u = defaultUpgrades.find((x) => x.id === id), l = level(s, id);
      if (!u || l >= u.maxLevel) throw Error("\u0423\u043B\u0443\u0447\u0448\u0435\u043D\u0438\u0435 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u043E");
      charge(s, u.levels[l].cost);
      s.upgradeLevels.find((x) => x.id === id).currentLevel++;
      if (id === "click-power") s.clickPower += u.levels[l].bonus;
      xp(s, 15 + l * 5);
      break;
    }
    case "buy-shop": {
      const item = shopItemsData.find((x) => x.id === id);
      if (!item || s.purchasedShop.some((x) => x.id === id)) throw Error("\u041F\u043E\u043A\u0443\u043F\u043A\u0430 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      const p = Number(a.price ?? item.basePrice);
      let multipliers = [1];
      if (item.categoryId === "cars") multipliers = carEngineOptions.flatMap((e) => carTrimOptions.map((t) => 1 + e.priceMultiplier + t.priceMultiplier));
      if (["ships", "planes"].includes(item.categoryId)) multipliers = [false, true].flatMap((c) => finishOptions.map((f) => 1 + (c ? crewOption.priceMultiplier : 0) + f.priceMultiplier));
      if (!multipliers.some((m) => Math.round(item.basePrice * m) === p)) throw Error("Invalid price");
      charge(s, p);
      s.purchasedShop.push({ id, price: p });
      xp(s, 40);
      break;
    }
    case "sell-shop": {
      const item = s.purchasedShop.find((x) => x.id === id);
      if (!item) throw Error("\u041D\u0435\u0442 \u043F\u0440\u0435\u0434\u043C\u0435\u0442\u0430");
      credit(s, Math.round(item.price * 0.25));
      s.purchasedShop = s.purchasedShop.filter((x) => x.id !== id);
      delete s.realEstateUpgrades[id];
      s.licensePlates = s.licensePlates.map((p) => p.assignedTo === id ? { ...p, assignedTo: null } : p);
      break;
    }
    case "buy-accessory": {
      const item = accessoryItemsData.find((x) => x.id === id);
      if (!item || s.purchasedAccessories.some((x) => x.id === id)) throw Error("\u041F\u043E\u043A\u0443\u043F\u043A\u0430 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      charge(s, item.basePrice);
      s.purchasedAccessories.push({ id, price: item.basePrice });
      xp(s, 30);
      break;
    }
    case "sell-accessory": {
      const item = s.purchasedAccessories.find((x) => x.id === id);
      if (!item || accessoryItemsData.find((x) => x.id === id)?.categoryId === "misc") throw Error("\u041F\u0440\u043E\u0434\u0430\u0436\u0430 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      credit(s, Math.round(item.price * 0.25));
      s.purchasedAccessories = s.purchasedAccessories.filter((x) => x.id !== id);
      break;
    }
    case "realestate-upgrade": {
      const item = s.purchasedShop.find((x) => x.id === id), u = REAL_ESTATE_UPGRADES.find((x) => x.id === a.upgradeId);
      if (!item || shopItemsData.find((x) => x.id === id)?.categoryId !== "realestate" || !u || (s.realEstateUpgrades[id] || []).includes(u.id)) throw Error("\u0423\u043B\u0443\u0447\u0448\u0435\u043D\u0438\u0435 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u043E");
      charge(s, Math.round(item.price * u.costRate));
      s.realEstateUpgrades[id] = [...s.realEstateUpgrades[id] || [], u.id];
      xp(s, 25);
      break;
    }
    case "license": {
      const country = String(a.country);
      if (s.entrepreneurLicense || !BUSINESS_LEGAL_FORMS[country]) throw Error("\u041B\u0438\u0446\u0435\u043D\u0437\u0438\u044F \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      charge(s, ENTREPRENEUR_LICENSE_COST);
      s.entrepreneurLicense = createLicense(country, now);
      xp(s, 20);
      break;
    }
    case "open-business": {
      const cat = businessCategories.find((x) => x.id === a.categoryId), name = String(a.name || "").trim();
      if (!cat || !s.entrepreneurLicense || name.length < 1 || name.length > 80 || s.businesses.length >= 1e3) throw Error("\u0420\u0435\u0433\u0438\u0441\u0442\u0440\u0430\u0446\u0438\u044F \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      const p = getBusinessPlan(cat.id);
      charge(s, p.registrationCost);
      s.businesses.push({ id: action.id, name, categoryId: cat.id, categoryName: cat.name, emoji: cat.emoji, investmentCost: p.registrationCost, incomePerHour: 0, taxRate: p.taxRate, taxDueAt: now + 2592e5, taxPaid: true, taxAmount: 0, createdAt: now, status: "registered", registrationNumber: `ENT-${action.id}`, completedSetupSteps: [], employeesHired: 0, employeesRequired: p.employeesRequired, grossRevenuePerHour: cat.baseIncomePerHour, salaryCostPerHour: 0, operatingCostPerHour: p.operatingCostPerHour, taxCostPerHour: 0 });
      xp(s, 75);
      break;
    }
    case "setup-business": {
      const b = business(), p = getBusinessPlan(b.categoryId), done = b.completedSetupSteps || [], step = p.steps.find((x) => !done.includes(x.id));
      if (b.status === "operating" || !step || step.id !== a.stepId) throw Error("\u041D\u0435\u0432\u0435\u0440\u043D\u044B\u0439 \u044D\u0442\u0430\u043F");
      charge(s, step.cost);
      b.completedSetupSteps = [...done, step.id];
      b.status = b.completedSetupSteps.length === p.steps.length ? "staffing" : step.stage;
      b.investmentCost += step.cost;
      xp(s, 35);
      break;
    }
    case "hire-business": {
      const b = business(), p = getBusinessPlan(b.categoryId);
      if (b.status === "operating" || b.completedSetupSteps?.length !== p.steps.length) throw Error("\u041A\u043E\u043C\u0430\u043D\u0434\u0430 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      charge(s, p.hiringCost);
      b.status = "operating";
      b.employeesHired = b.employeesRequired = p.employeesRequired;
      b.salaryCostPerHour = p.employeesRequired * p.salaryPerEmployee;
      b.operatingCostPerHour = p.operatingCostPerHour;
      b.taxCostPerHour = (b.grossRevenuePerHour || 0) * p.taxRate;
      b.incomePerHour = calculateBusinessNet(b);
      b.investmentCost += p.hiringCost;
      xp(s, 80);
      break;
    }
    case "sell-business": {
      const b = business();
      credit(s, b.investmentCost * 0.45);
      s.businesses = s.businesses.filter((x) => x.id !== id);
      break;
    }
    case "merge-business": {
      const m = businessMergers.find((x) => x.id === id);
      if (!m) throw Error("\u041D\u0435\u0442 \u0440\u0435\u0446\u0435\u043F\u0442\u0430");
      const consumed = [];
      for (const cat of m.requiredCategories) {
        const b = s.businesses.find((x) => x.categoryId === cat && x.status === "operating" && !consumed.includes(x));
        if (!b) throw Error("\u041D\u0435 \u0445\u0432\u0430\u0442\u0430\u0435\u0442 \u043F\u0440\u0435\u0434\u043F\u0440\u0438\u044F\u0442\u0438\u0439");
        consumed.push(b);
      }
      const { prices } = income(s, now);
      if (s.stockHoldings.reduce((n, h) => n + prices.stocks[h.assetId].current * h.quantity, 0) < (m.minStockPortfolio || 0) || s.cryptoHoldings.reduce((n, h) => n + prices.crypto[h.assetId].current * h.quantity, 0) < (m.minCryptoPortfolio || 0) || s.purchasedShop.filter((x) => shopItemsData.find((d) => d.id === x.id)?.categoryId === "islands").length < (m.minIslandCount || 0) || s.purchasedShop.filter((x) => shopItemsData.find((d) => d.id === x.id)?.categoryId === "realestate").reduce((n, x) => n + x.price, 0) < (m.minRealEstateValue || 0)) throw Error("\u041D\u0435 \u0432\u044B\u043F\u043E\u043B\u043D\u0435\u043D\u044B \u0443\u0441\u043B\u043E\u0432\u0438\u044F \u043E\u0431\u044A\u0435\u0434\u0438\u043D\u0435\u043D\u0438\u044F");
      s.businesses = s.businesses.filter((x) => !consumed.includes(x));
      s.businesses.push(migrateBusiness({ id: action.id, name: m.name, categoryId: m.id, categoryName: m.name, emoji: m.emoji, investmentCost: consumed.reduce((n, b) => n + b.investmentCost, 0), incomePerHour: m.resultIncomePerHour, taxRate: 0.13, taxDueAt: now + 2592e5, taxPaid: true, taxAmount: 0, createdAt: now }));
      xp(s, 150);
      break;
    }
    case "buy-stock":
    case "sell-stock":
    case "buy-crypto":
    case "sell-crypto": {
      const quantity = Number(a.quantity), crypto2 = action.type.endsWith("crypto"), buy = action.type.startsWith("buy"), assets = crypto2 ? cryptoAssets : stockAssets, asset = assets.find((x) => x.id === id);
      if (!asset || !Number.isFinite(quantity) || quantity <= 0 || quantity > MAX_MONEY) throw Error("Invalid quantity");
      const limit = "availableShares" in asset ? asset.availableShares : asset.availableSupply;
      const holdings = crypto2 ? s.cryptoHoldings : s.stockHoldings, h = holdings.find((x) => x.assetId === id);
      const price = (crypto2 ? income(s, now).prices.crypto : income(s, now).prices.stocks)[id].current;
      if (buy) {
        if (quantity + (h?.quantity || 0) > limit) throw Error("\u041F\u0440\u0435\u0432\u044B\u0448\u0435\u043D \u043E\u0431\u044A\u0451\u043C \u0432\u044B\u043F\u0443\u0441\u043A\u0430");
        charge(s, quantity * price);
        if (h) {
          h.avgBuyPrice = (h.quantity * h.avgBuyPrice + quantity * price) / (h.quantity + quantity);
          h.quantity += quantity;
        } else holdings.push({ assetId: id, quantity, avgBuyPrice: price });
      } else {
        if (!h || quantity > h.quantity) throw Error("\u041D\u0435 \u0445\u0432\u0430\u0442\u0430\u0435\u0442 \u0430\u043A\u0442\u0438\u0432\u043E\u0432");
        credit(s, quantity * price);
        const profit = Math.max(0, (price - h.avgBuyPrice) * quantity);
        if (crypto2) s.totalEarnedCrypto += profit;
        else s.totalEarnedTrading += profit;
        h.quantity -= quantity;
        if (!h.quantity) holdings.splice(holdings.indexOf(h), 1);
      }
      break;
    }
    case "buy-card": {
      const d = BANK_CARD_DESIGNS.find((x) => x.id === id);
      if (!d || d.unlockLevel || s.bankCard.ownedIds.includes(id)) throw Error("\u041A\u0430\u0440\u0442\u0430 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u0430");
      charge(s, d.price);
      s.bankCard.ownedIds.push(id);
      s.bankCard.activeId = id;
      break;
    }
    case "select-card": {
      s.bankCard = normalizeBankCardState(s.bankCard, progressionFromXp(s.playerXp).level);
      if (!s.bankCard.ownedIds.includes(id)) throw Error("\u041A\u0430\u0440\u0442\u0430 \u0437\u0430\u0431\u043B\u043E\u043A\u0438\u0440\u043E\u0432\u0430\u043D\u0430");
      s.bankCard.activeId = id;
      break;
    }
    case "customize-card": {
      if (!/^\d{4}$/.test(String(a.customNumber)) || !/^(0[1-9]|1[0-2])\/\d{2}$/.test(String(a.expiresAt)) || a.customColor !== null && !/^#[0-9a-f]{6}$/i.test(String(a.customColor))) throw Error("\u041D\u0435\u0432\u0435\u0440\u043D\u044B\u0435 \u0440\u0435\u043A\u0432\u0438\u0437\u0438\u0442\u044B");
      s.bankCard = { ...s.bankCard, customNumber: String(a.customNumber), expiresAt: String(a.expiresAt), customColor: a.customColor };
      break;
    }
    case "buy-plate": {
      const country = String(a.country || "");
      if (!PLATE_COUNTRIES.some((c) => c.id === country) || typeof a.isCustom !== "boolean") throw Error("\u041D\u0435\u0432\u0435\u0440\u043D\u044B\u0439 \u043D\u043E\u043C\u0435\u0440");
      let text = a.isCustom ? String(a.text || "").trim().toUpperCase() : generateRandomPlate(country);
      if (a.isCustom && !validateCustomPlate(text, country)) throw Error("\u041D\u0435\u0432\u0435\u0440\u043D\u044B\u0439 \u043D\u043E\u043C\u0435\u0440");
      if (!a.isCustom) {
        for (let n = 0; n < 50 && s.licensePlates.some((p) => p.text === text && p.country === country); n++) text = generateRandomPlate(country);
      }
      if (s.licensePlates.some((p) => p.text === text && p.country === country)) throw Error("\u041D\u043E\u043C\u0435\u0440 \u0443\u0436\u0435 \u0435\u0441\u0442\u044C");
      charge(s, a.isCustom ? 25e3 : 5e3);
      s.licensePlates.push({ id: action.id, text, country, assignedTo: null, isCustom: a.isCustom });
      break;
    }
    case "assign-plate": {
      const plate = s.licensePlates.find((x) => x.id === id), carId = a.carId === null ? null : String(a.carId);
      if (!plate || carId && !s.purchasedShop.some((x) => x.id === carId && shopItemsData.find((d) => d.id === x.id)?.categoryId === "cars")) throw Error("\u041D\u0430\u0437\u043D\u0430\u0447\u0435\u043D\u0438\u0435 \u043D\u0435\u0434\u043E\u0441\u0442\u0443\u043F\u043D\u043E");
      s.licensePlates = s.licensePlates.map((p) => ({ ...p, assignedTo: p.id === id ? carId : carId && p.assignedTo === carId ? null : p.assignedTo }));
      break;
    }
    case "delete-plate":
      if (!s.licensePlates.some((x) => x.id === id)) throw Error("\u041D\u0435\u0442 \u043D\u043E\u043C\u0435\u0440\u0430");
      s.licensePlates = s.licensePlates.filter((x) => x.id !== id);
      break;
    default:
      throw Error("Unknown game action");
  }
  s.bankCard = normalizeBankCardState(s.bankCard, progressionFromXp(s.playerXp).level);
  s.savedAt = now;
  updateAchievements(s, now);
  return s;
}
function gameView(s, now = Date.now()) {
  const i = income(s, now), p = progressionFromXp(s.playerXp);
  return { ...s, upgrades: defaultUpgrades.map((u) => ({ ...u, currentLevel: level(s, u.id) })), shopItems: shopItemsData.map((d) => ({ id: d.id, name: d.name, emoji: d.emoji, category: d.categoryId, purchased: s.purchasedShop.some((x) => x.id === d.id), price: s.purchasedShop.find((x) => x.id === d.id)?.price || d.basePrice })), accessoryItems: accessoryItemsData.map((d) => ({ id: d.id, name: d.name, emoji: d.emoji, category: d.categoryId, purchased: s.purchasedAccessories.some((x) => x.id === d.id), price: d.basePrice })), stockPrices: i.prices.stocks, cryptoPrices: i.prices.crypto, playerLevel: p.level, levelStartXp: p.levelStartXp, nextLevelXp: p.nextLevelXp, levelProgress: p.progress, hourlyIncomeRent: i.rent, hourlyIncomeBusiness: i.business, hourlyIncomeDividends: i.dividends, hourlyIncome: i.rent + i.business + i.dividends, passiveIncome: (i.rent + i.business + i.dividends) / 3600, netWorth: assetWorth(s, now), totalTaxDue: 0 };
}
