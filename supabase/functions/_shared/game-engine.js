var EPOCH = Date.UTC(2025, 0, 1);
var YEAR = 365.25 * 864e5;
var hash = (value) => {
  let h = 2166136261;
  for (let i = 0; i < value.length; i++) h = Math.imul(h ^ value.charCodeAt(i), 16777619);
  return (h >>> 0) / 4294967295;
};
var smoothNoise = (id, time, knotMs) => {
  const knot = Math.floor(time / knotMs);
  const part = time / knotMs - knot;
  const eased = part * part * (3 - 2 * part);
  const a = hash(`${id}:${knot}`) * 2 - 1;
  const b = hash(`${id}:${knot + 1}`) * 2 - 1;
  return a + (b - a) * eased;
};
var roundPrice = (price) => Number(price.toFixed(price < 1 ? 4 : 2));
function marketPriceAt(asset, kind, timestamp = Date.now()) {
  const years = (timestamp - EPOCH) / YEAR;
  const seed = hash(asset.id);
  const annualTrend = kind === "stocks" ? 0.035 + seed * 0.075 : 0.06 + seed * 0.16;
  const macro = Math.sin(years * Math.PI * (1.1 + seed) + seed * 8) * asset.volatility * 0.22;
  const medium = Math.sin(years * Math.PI * 11 + seed * 20) * asset.volatility * 0.08;
  const noise = smoothNoise(asset.id, timestamp, kind === "stocks" ? 12 * 36e5 : 6 * 36e5) * asset.volatility * 0.055;
  return roundPrice(Math.max(asset.basePrice * 0.08, asset.basePrice * Math.exp(annualTrend * years + macro + medium + noise)));
}
function marketHistory(asset, kind, range, now = Date.now()) {
  const config = MARKET_RANGES.find((item) => item.id === range) || MARKET_RANGES[0];
  return Array.from({ length: config.points }, (_, index) => {
    const time = now - config.durationMs + config.durationMs * index / (config.points - 1);
    return { time, value: marketPriceAt(asset, kind, time) };
  });
}
function sharedMarketPrices(stocks, crypto2, now = Date.now()) {
  const make = (assets, kind) => Object.fromEntries(assets.map((asset) => {
    const history = marketHistory(asset, kind, "1d", now).map((point) => point.value);
    return [asset.id, { current: history[history.length - 1], history }];
  }));
  return { stocks: make(stocks, "stocks"), crypto: make(crypto2, "crypto") };
}

// src/game/progression.ts
function totalXpForLevel(level2) {
  const safeLevel = Math.max(1, Math.floor(level2));
  return Math.floor(100 * Math.pow(safeLevel - 1, 1.65));
}
function levelFromXp(xp2) {
  const safeXp = Math.min(1e9, Math.max(0, Math.floor(Number.isFinite(xp2) ? xp2 : 0)));
  let level2 = Math.max(1, Math.floor(Math.pow(safeXp / 100, 1 / 1.65)) + 1);
  while (totalXpForLevel(level2 + 1) <= safeXp) level2 += 1;
  while (totalXpForLevel(level2) > safeXp && level2 > 1) level2 -= 1;
  return level2;
}
function rewardForLevel(level2) {
  return Math.max(0, Math.floor(level2)) * Math.max(0, Math.floor(level2)) * 250;
}
function rewardsBetweenLevels(previousLevel, nextLevel) {
  let reward = 0;
  for (let level2 = previousLevel + 1; level2 <= nextLevel; level2 += 1) {
    reward += rewardForLevel(level2);
  }
  return reward;
}
function progressionFromXp(xp2) {
  const playerXp = Math.min(1e9, Math.max(0, Math.floor(Number.isFinite(xp2) ? xp2 : 0)));
  const level2 = levelFromXp(playerXp);
  const levelStartXp = totalXpForLevel(level2);
  const nextLevelXp = totalXpForLevel(level2 + 1);
  const progress = nextLevelXp === levelStartXp ? 1 : (playerXp - levelStartXp) / (nextLevelXp - levelStartXp);
  return { level: level2, levelStartXp, nextLevelXp, progress };
}

